// The Cell Explorer's words and colours, copied out of the specification's §5.1.1–5.1.4 (the animal, plant and
// bacterial cells' tables and the Compare table) by a script, cell for cell: the cards' Function lines are these
// words verbatim (§5.1.6). Never edited by hand; CellExplorerModel.swift reads it (CEParts).

/// A colour from a table's colour cell: what it colours ("envelope", "grana"; empty for the only one), light, dark.
struct CESpecColour: Sendable {
    let name: String
    let light: String
    let dark: String
    init(_ name: String, _ light: String, _ dark: String) {
        self.name = name
        self.light = light
        self.dark = dark
    }
}

